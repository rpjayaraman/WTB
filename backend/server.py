# ── XTrace → Standard VCD Converter ─────────────────────────────
# Ported verbatim from compile_server.py — converts xezim's
# compact XTrace format to standard IEEE VCD for the waveform viewer.
def convert_xtrace_to_standard_vcd(xtrace_text: str) -> str:
    lines = xtrace_text.splitlines()
    sym_map = {}
    time = 0

    out = [
        '$date\n  Generated by xezim converter\n$end',
        '$version\n  xezim 0.1\n$end',
        '$timescale\n  1ns\n$end',
        '$scope module top $end'
    ]

    in_dict = False
    in_trace = False
    sym_code = 33  # ASCII '!'

    for line in lines:
        line = line.strip()
        if line == '@section dict':
            in_dict = True
            continue
        elif line == '@section trace':
            in_dict = False
            in_trace = True
            out.append('$enddefinitions $end')
            out.append('#0')
            out.append('$dumpvars')
            continue

        if in_dict and line.startswith('S,'):
            parts = line.split(',')
            sig_id   = parts[1]
            sig_name = parts[3]
            sig_type = parts[4] if len(parts) > 4 else 'bit'
            width = 1
            if sig_type == 'u8':   width = 8
            elif sig_type == 'u16': width = 16
            elif sig_type == 'u32': width = 32
            elif sig_type == 'u64': width = 64

            while sym_code in (34, 39, 92):
                sym_code += 1
            sym = chr(sym_code)
            sym_code += 1
            sym_map[sig_id] = (sig_name, width, sym)
            out.append(f'$var wire {width} {sym} {sig_name} $end')

        elif in_trace:
            if line.startswith('T,'):
                t_str = line.split(',')[1]
                if t_str.startswith('+'):
                    time += int(t_str[1:])
                else:
                    time = int(t_str)
                out.append(f'#{time}')
            elif line.startswith('P,') or line.startswith('N,full,') or line.startswith('D,'):
                parts = line.split(',')
                items = parts[1:]
                for item in items:
                    if '=' in item:
                        k, v = item.split('=', 1)
                        if k in sym_map:
                            s_name, width, sym = sym_map[k]
                            val_str = v.replace('0x', '').replace('0b', '')
                            if width == 1:
                                bit_val = '1' if '1' in val_str else '0'
                                out.append(f'{bit_val}{sym}')
                            else:
                                try:
                                    num = int(val_str, 16) if '0x' in v else (int(val_str, 2) if '0b' in v else int(val_str))
                                    b_val = format(num, f'0{width}b')
                                except Exception:
                                    b_val = '0' * width
                                out.append(f'b{b_val} {sym}')
                    elif len(parts) >= 3 and parts[0] == 'D':
                        k = parts[1]
                        v = parts[2]
                        if k in sym_map:
                            s_name, width, sym = sym_map[k]
                            if width == 1:
                                bit_val = '1' if '1' in v else '0'
                                out.append(f'{bit_val}{sym}')
                            else:
                                try:
                                    num = int(v, 16) if '0x' in v else (int(v, 2) if '0b' in v else int(v))
                                    b_val = format(num, f'0{width}b')
                                except Exception:
                                    b_val = '0' * width
                                out.append(f'b{b_val} {sym}')

    out.append('$end')
    return '\n'.join(out)



# ── Main Simulation Endpoint ─────────────────────────────────────
@app.post("/lint")
@limiter.limit("10/minute")
async def lint(request: Request, body: SimRequest):
    code    = body.code
    command = body.command

    # Resolve cloud xezim path if command still carries Mac-local paths
    command = command.replace(
        '/Users/mac/xezim-workspace/xezim/target/release/xezim', XEZIM_BIN
    ).replace(
        '/Users/mac/xezim-workspace/uvm-1.2/src', UVM_12_SRC
    )

    tmp_dir = tempfile.mkdtemp(prefix="wtb_sim_")
    try:
        return await _run_simulation(code, command, tmp_dir)
    finally:
        shutil.rmtree(tmp_dir, ignore_errors=True)


async def _run_simulation(code: str, command: str, tmp_dir: str):
    temp_filename = os.path.join(tmp_dir, 'scratch.sv')
    vcd_filename  = 'wave.vcd'

    # ── Auto-detect VCD filename from user code ──────────────────
    match = re.search(r'\$dumpfile\s*\(\s*["\']([^"\']+)["\']\s*\)', code)
    if match:
        vcd_filename = match.group(1)
    elif 'endmodule' in code and '--simulate' in command:
        dump_code = '\ninitial begin\n  $dumpfile("wave.vcd");\n  $dumpvars(0);\nend\n'
        parts = code.rsplit('endmodule', 1)
        code = parts[0] + dump_code + 'endmodule' + parts[1]
        vcd_filename = 'wave.vcd'

    # ── Write SV source ──────────────────────────────────────────
    # Ensure source ends with a newline to satisfy POSIX/Verilator
    if not code.endswith('\n'):
        code += '\n'
        
    with open(temp_filename, 'w') as f:
        f.write(code)

    # ── Parse and Sanitize command safely (no shell=True) ────────
    # Split the raw command line into distinct arguments
    import shlex
    raw_args = shlex.split(command)
    if not raw_args:
        return JSONResponse(status_code=400, content={'error': 'Empty command payload', 'success': False})

    # Strict whitelist validation to block malicious shells, paths, or injection characters
    allowed_binaries = {'xezim', 'verilator', XEZIM_BIN, 'vvp', 'iverilog'}
    binary_invoked = os.path.basename(raw_args[0])
    if binary_invoked not in allowed_binaries:
        return JSONResponse(status_code=400, content={
            'error': f'Disallowed execution target: {binary_invoked}',
            'success': False
        })

    # Resolve executable path
    cmd_args = []
    if binary_invoked == 'xezim':
        cmd_args.append(XEZIM_BIN)
    else:
        cmd_args.append(raw_args[0])

    # Validate remaining arguments against shell metacharacters (allow $ for $FILE variable placeholder)
    dangerous_chars = re.compile(r'[;&|`><*\?\[\]\{\}\(\)\!\#\~]')
    for arg in raw_args[1:]:
        # Remove local workspace prefix mappings dynamically if present
        if '/Users/mac/xezim-workspace/uvm-1.2/src' in arg:
            arg = arg.replace('/Users/mac/xezim-workspace/uvm-1.2/src', UVM_12_SRC)
        
        # Guard against injection tokens or directory traversal attempts
        if dangerous_chars.search(arg) or '..' in arg:
            return JSONResponse(status_code=400, content={
                'error': f'Forbidden characters or paths detected in arguments: {arg}',
                'success': False
            })
        
        if arg == '$FILE':
            cmd_args.append(temp_filename)
        else:
            cmd_args.append(arg)

    # Ensure $FILE is appended if not explicitly present in inputs
    if temp_filename not in cmd_args:
        cmd_args.append(temp_filename)

    # Automatically add Warning suppression flag sets for Verilator runs
    if 'verilator' in binary_invoked:
        if '-Wno-DECLFILENAME' not in cmd_args:
            cmd_args.append('-Wno-DECLFILENAME')
        if '-Wno-EOFNEWLINE' not in cmd_args:
            cmd_args.append('-Wno-EOFNEWLINE')

    # Automatically add XTrace dumping configs for xezim runs
    if 'xezim' in binary_invoked and '--simulate' in cmd_args and '--xtrace' not in cmd_args:
        cmd_args.extend(['--xtrace', os.path.join(tmp_dir, 'wave.vcd')])

    print(f"[WTB] Executing structured command: {cmd_args}")

    # ── Safe Execution without shell=True ────────────────────────
    try:
        result = subprocess.run(
            cmd_args,
            cwd=tmp_dir,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            timeout=120
        )
    except subprocess.TimeoutExpired:
        return JSONResponse(status_code=200, content={
            'exit_code': -1,
            'stdout': '',
            'stderr': '[TIMEOUT] Simulation exceeded 120s limit. Try a shorter simulation or reduce $finish time.',
            'success': False
        })

    # ── Collect VCD output ───────────────────────────────────────
    vcd_text_str = None
    for fname in os.listdir(tmp_dir):
        if fname.endswith('.vcd'):
            fpath = os.path.join(tmp_dir, fname)
            if os.path.getsize(fpath) < 50 * 1024 * 1024:  # skip >50MB
                try:
                    with open(fpath, 'r', errors='ignore') as vf:
                        raw_vcd = vf.read()
                    if raw_vcd.startswith('@xtrace'):
                        vcd_text_str = convert_xtrace_to_standard_vcd(raw_vcd)
                    else:
                        vcd_text_str = raw_vcd
                    print(f"[WTB] VCD ready: {len(vcd_text_str)} chars from {fname}")
                except Exception as e:
                    print(f"[WTB] VCD read error: {e}")
                break

    # ── Collect coverage JSON ────────────────────────────────────
    cov_data = None
    cov_path = os.path.join(tmp_dir, 'xezim_cov.json')
    if os.path.exists(cov_path):
        try:
            with open(cov_path, 'r') as cf:
                cov_data = json.load(cf)
        except Exception as e:
            print(f"[WTB] Coverage read error: {e}")

    # ── Build and return response ────────────────────────────────
    response = {
        'exit_code': result.returncode,
        'stdout':    result.stdout,
        'stderr':    result.stderr,
        'success':   result.returncode == 0,
    }
    if vcd_text_str:
        response['vcd_text'] = vcd_text_str
    if cov_data:
        response['coverage'] = cov_data

    return response
